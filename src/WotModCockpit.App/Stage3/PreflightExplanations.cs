    /// <summary>
    /// Заголовки для кодов, у которых НЕТ своего класса правила в Core, и потому нет
    /// и своего <c>IPreflightRule.Title</c>: <c>UnknownApiRule</c> зарегистрирован под
    /// <c>WOT002</c>, а выдаёт ещё два кода. Без этих строк справочник правил показывал бы
    /// три разные категории находок под одним и тем же именем.
    /// </summary>
    private static readonly Dictionary<string, string> Titles = new(StringComparer.OrdinalIgnoreCase)
    {
        ["WOT003"] = "Модуль клиента есть, а имени в нём нет",
        ["WOT004"] = "Обращение к атрибуту, которого в модуле клиента нет"
    };

    /// <summary>
    /// Развёрнутое объяснение правила.
    /// </summary>
    /// <param name="ruleId">Код правила.</param>
    /// <returns>Абзац либо пустая строка, если правило неизвестно (например, находка pyright).</returns>
    public static string For(string? ruleId)
        => ruleId is not null && Texts.TryGetValue(ruleId, out string? text) ? text : string.Empty;

    /// <summary>
    /// Собственный заголовок кода находки.
    /// </summary>
    /// <param name="ruleId">Код правила.</param>
    /// <returns>
    /// Заголовок либо пустая строка — тогда берётся <c>IPreflightRule.Title</c> класса,
    /// который этот код выдал.
    /// </returns>
    public static string TitleFor(string? ruleId)
        => ruleId is not null && Titles.TryGetValue(ruleId, out string? title) ? title : string.Empty;
