namespace WotModCockpit.Core.Abstractions;

/// <summary>
/// Следит за <c>python.log</c> и отдаёт новые строки по мере их появления.
/// <para>
/// ГЛАВНАЯ СЛОЖНОСТЬ, ради которой существует этот интерфейс: движок открывает лог в режиме дозаписи
/// ('a'), и, когда файл дорастает до 2048 КБ, УСЕКАЕТ его до последних 512 КБ. То есть длина файла
/// внезапно уменьшается, а содержимое сдвигается. Наивный tail «читать с сохранённого смещения»
/// после такого выдаёт мусор или вечно ждёт. Реализация ОБЯЗАНА:
/// </para>
/// <list type="number">
///   <item>заметить, что текущая длина файла стала МЕНЬШЕ прочитанного смещения;</item>
///   <item>поднять <see cref="FileTruncated"/>;</item>
///   <item>сбросить смещение в 0 и продолжить чтение с начала нового содержимого.</item>
/// </list>
/// <para>Прочие обязательные требования:</para>
/// <list type="bullet">
///   <item>Файл открывать с <c>FileShare.ReadWrite | FileShare.Delete</c> — игра держит его открытым
///         на запись, без этих флагов открыть не выйдет.</item>
///   <item>Отсутствие файла — НЕ ошибка: <see cref="Start"/> должен спокойно ждать его появления
///         (игра ещё не запускалась) и начать читать, когда файл возникнет.</item>
///   <item>Замена файла целиком (удалили и создали заново) детектируется по смене
///         идентичности файла или по уменьшению длины — реакция та же, что на усечение.</item>
///   <item>Кодировка — UTF-8 без BOM; битые байты не должны ронять чтение (заменять на U+FFFD).</item>
///   <item>Строки отдаются БЕЗ завершающего <c>\r\n</c>. Хвост без перевода строки не отдаётся,
///         пока строка не дописана целиком — иначе UI будет мигать полустроками.</item>
///   <item>События поднимаются из ФОНОВОГО потока. В WPF потребитель обязан маршалить в UI-поток сам.</item>
/// </list>
/// </summary>
public interface ILogTailer : IDisposable
{
    /// <summary>Абсолютный путь к отслеживаемому файлу (обычно <c>&lt;game&gt;\python.log</c>).</summary>
    string FilePath { get; }

    /// <summary>true между успешным <see cref="Start"/> и <see cref="Stop"/>.</summary>
    bool IsRunning { get; }

    /// <summary>
    /// Прочитана очередная полная строка. Аргумент — текст строки без перевода строки.
    /// Поднимается из фонового потока, по одной строке на событие, строго в порядке файла.
    /// </summary>
    event EventHandler<string>? LineRead;

    /// <summary>
    /// Файл усечён движком (или подменён). Поднимается ДО первой строки нового содержимого.
    /// Потребитель обязан на это событие: сбросить накопленное состояние склейки traceback,
    /// признать недействительными все ранее выданные <c>LogEntry.ByteOffset</c> и (по желанию)
    /// вставить в ленту разделитель «лог усечён игрой».
    /// </summary>
    event EventHandler? FileTruncated;

    /// <summary>
    /// Ошибка чтения, из-за которой слежение остановлено или пропущено (файл занят, отказ в доступе).
    /// Слежение при этом НЕ падает: реализация повторяет попытку. Событие нужно только для показа в UI.
    /// </summary>
    event EventHandler<Exception>? Error;

    /// <summary>
    /// Начинает слежение. Идемпотентен: повторный вызов при <see cref="IsRunning"/> = true ничего не делает.
    /// <para>
    /// Перед переходом в режим хвоста реализация «прогревает» ленту: читает последние
    /// <c>primeTailBytes</c> байт файла и отдаёт их через <see cref="LineRead"/>, отбросив первую
    /// (заведомо обрезанную посередине) строку. <c>primeTailBytes</c> = 0 — читать только новое.
    /// </para>
    /// </summary>
    /// <param name="primeTailBytes">Сколько последних байт прочитать при старте. По умолчанию 64 КБ.</param>
    void Start(int primeTailBytes = 64 * 1024);

    /// <summary>
    /// Останавливает слежение и освобождает дескриптор файла.
    /// Идемпотентен. После него события больше не поднимаются.
    /// </summary>
    void Stop();
}

/// <summary>Фабрика тейлеров: путь к логу известен только после выбора установки игры.</summary>
public interface ILogTailerFactory
{
    /// <summary>
    /// Создаёт остановленный тейлер для указанного файла. Вызывающий владеет им и обязан освободить.
    /// </summary>
    /// <param name="filePath">Абсолютный путь к <c>python.log</c>. Файл может не существовать.</param>
    /// <returns>Новый экземпляр в состоянии <see cref="ILogTailer.IsRunning"/> = false.</returns>
    ILogTailer Create(string filePath);
}
