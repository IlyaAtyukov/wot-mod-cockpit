using WotModCockpit.Core.Models;

namespace WotModCockpit.Core.Abstractions;

/// <summary>
/// Определяет установку игры и её АКТУАЛЬНУЮ версию по <c>paths.xml</c>.
/// <para>
/// Почему нельзя просто взять самый большой номер каталога в <c>mods\</c>: там годами копятся каталоги
/// от <c>1.28.0.0</c> до <c>1.44.0.0</c> (проверено на реальной установке), и активен из них РОВНО ОДИН —
/// тот, что записан в <c>paths.xml</c>. Единственный источник истины — этот файл.
/// </para>
/// <para>
/// Что разбирать в <c>&lt;корень&gt;\paths.xml</c>: внутри <c>&lt;root&gt;&lt;Paths&gt;</c> лежат элементы <c>&lt;Path&gt;</c>.
/// Нужны два из них (порядок в файле значим и должен быть сохранён при анализе перекрытия):
/// <code>
/// &lt;Path cacheSubdirs="true"&gt;./res_mods/1.44.0.0&lt;/Path&gt;                          ← res_mods, идёт ПЕРВЫМ
/// &lt;Path mask="*.mtmod" mode="recursive" root="res"&gt;./mods/1.44.0.0&lt;/Path&gt;      ← mods, идёт вторым
/// </code>
/// Остальные <c>&lt;Path&gt;</c> (в частности замыкающий <c>./res</c>) и весь блок <c>&lt;Packages&gt;</c> игнорируются.
/// Версия берётся из последнего сегмента этих путей (<c>1.44.0.0</c>); если сегменты res_mods и mods
/// разошлись — считать истиной тот, что у строки с <c>mask="*.mtmod"</c>, и вернуть установку всё равно.
/// </para>
/// </summary>
public interface IGameInstallLocator
{
    /// <summary>
    /// Разбирает <c>&lt;rootPath&gt;\paths.xml</c> и возвращает описание установки.
    /// </summary>
    /// <param name="rootPath">
    /// Каталог-кандидат — там, где лежат <c>Tanki.exe</c> и <c>paths.xml</c>. Относительный путь допустим,
    /// реализация приводит его к абсолютному.
    /// </param>
    /// <returns>
    /// Заполненный <see cref="GameInstall"/> либо <c>null</c>, если это не установка игры.
    /// <c>null</c> ОБЯЗАН возвращаться (а не бросаться исключение) во всех обыденных случаях:
    /// каталог не существует, нет <c>paths.xml</c>, файл не разбирается как XML, в нём нет ни одной
    /// подходящей строки <c>&lt;Path&gt;</c>, <c>rootPath</c> пуст или состоит из пробелов.
    /// Исключения допустимы только на действительно неожиданном (например, отказ в доступе к диску).
    /// </returns>
    /// <remarks>
    /// Метод ТОЛЬКО ЧИТАЕТ. Он не создаёт отсутствующие <c>mods\&lt;ver&gt;</c>/<c>res_mods\&lt;ver&gt;</c> —
    /// пути в результате могут указывать на несуществующие каталоги, и это нормально.
    /// </remarks>
    GameInstall? Detect(string rootPath);
}
