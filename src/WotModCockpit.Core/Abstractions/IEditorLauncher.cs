namespace WotModCockpit.Core.Abstractions;

/// <summary>
/// Открывает файл во внешнем редакторе на нужной строке. Кокпит — НЕ редактор кода:
/// запись кода остаётся за VS Code, кокпит только приводит разработчика в нужное место.
/// <para>
/// Установщик VS Code кладёт в PATH обёртку <c>&lt;папка VS Code&gt;\bin\code</c>
/// (рядом в родительском каталоге лежит и <c>Code.exe</c>). Рабочая команда перехода:
/// </para>
/// <code>code --goto "C:\путь\к\файлу.py:67"</code>
/// <para>
/// Тонкость: <c>bin\code</c> — это .cmd-обёртка, её нельзя запускать с
/// <c>UseShellExecute = false</c> напрямую как .exe без указания расширения; надёжнее либо
/// вызывать <c>Code.exe</c>, либо запускать <c>cmd /c code ...</c>. Выбор — за реализацией,
/// но упасть с <c>Win32Exception</c> она не имеет права (см. ниже).
/// </para>
/// </summary>
public interface IEditorLauncher
{
    /// <summary>
    /// true, если редактор найден и <see cref="OpenAt"/> имеет шанс сработать.
    /// UI по этому свойству гасит пункт «открыть в редакторе».
    /// Свойство ДЕШЁВОЕ: результат поиска кэшируется, диск при каждом обращении не опрашивается.
    /// </summary>
    bool IsAvailable { get; }

    /// <summary>
    /// Открывает файл в редакторе и ставит курсор на строку.
    /// </summary>
    /// <param name="filePath">Абсолютный путь к существующему файлу. Пробелы в пути — норма, экранирование на реализации.</param>
    /// <param name="line">Номер строки, 1-based. Значения &lt;= 0 трактуются как 1.</param>
    /// <remarks>
    /// Метод НЕ бросает исключений на бытовые неудачи: нет редактора, файла не существует,
    /// процесс не запустился. Такие случаи просто ничего не делают
    /// (реализация может сообщить о них через <see cref="LaunchFailed"/>). Причина в том,
    /// что метод дёргается из обработчика двойного клика по строке лога, и падение UI из-за
    /// отсутствующего VS Code недопустимо.
    /// </remarks>
    void OpenAt(string filePath, int line);

    /// <summary>
    /// Открывает каталог как рабочую папку редактора (<c>code "&lt;dir&gt;"</c>).
    /// Используется кнопкой «открыть проект в VS Code».
    /// </summary>
    /// <param name="folderPath">Абсолютный путь к каталогу.</param>
    void OpenFolder(string folderPath);

    /// <summary>
    /// Поднимается, когда запустить редактор не удалось. Нужно, чтобы UI показал подсказку
    /// «укажите путь к VS Code в настройках», не превращая это в исключение.
    /// </summary>
    event EventHandler<string>? LaunchFailed;
}
